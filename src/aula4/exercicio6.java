package aula4;

public class exercicio6 {

        public static void main(String[] args) {
            int num1 = 15;
            int num2 = 10;

            System.out.println("num1 > num2: " + (num1 > num2));   // true
            System.out.println("num1 < num2: " + (num1 < num2));   // false
            System.out.println("num1 >= num2: " + (num1 >= num2)); // true
            System.out.println("num1 <= num2: " + (num1 <= num2)); // false
            System.out.println("num1 == num2: " + (num1 == num2)); // false
            System.out.println("num1 != num2: " + (num1 != num2)); // true
        }
    }

